export const cmsText = (english, language) => language === 'sv-se'
    ? (reviewedSwedish[english] || generatedSwedish[english] || english)
    : english

export const cmsLegacyText = (swedish, language) => language === 'sv-se'
    ? swedish
    : (reviewedEnglish[swedish] || generatedEnglish[swedish] || swedish)

export const cmsTextGlobal = (text) => {
    const key = text.trim()
    if (!key) return text
    const translated = activeLanguage === 'sv-se'
        ? (generatedEnglish[key] ? key : cmsText(key, activeLanguage))
        : (reviewedEnglish[key] || generatedEnglish[key] || key)
    return translated === key ? text : text.replace(key, translated)
}
